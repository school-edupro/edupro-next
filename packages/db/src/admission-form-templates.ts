import type { AdmissionField, AdmissionFormDef } from './admission-engine';

/**
 * Ready admission forms (docs/design/39, part 1) from the reference registration forms: the general form
 * (Class IX and others, 8 tabs) and the Class XI form for the written test (stream, subjects, marks with
 * cut-offs). A school copies one and changes it in the builder. Option lists come from the school's
 * Profile lists and masters, not from here; `maps` sends an answer to the student master on Admit and
 * `copy` keeps an answer the master has no field for as an additional student field.
 */

const PARENT = (
  p: 'father' | 'mother',
  step: string,
  opts: { alumni: boolean },
): AdmissionField[] => {
  const P = p === 'father' ? 'Father' : 'Mother';
  const single = p === 'father' ? 'Mother Only' : 'Father Only';
  // hidden (and so not asked) when the other parent is the single parent; the tab goes with them
  const req = [
    {
      logic: 'all' as const,
      action: 'hide' as const,
      conditions: [{ field: 'single_parent', op: 'eq' as const, value: single }],
    },
  ];
  const out: AdmissionField[] = [
    {
      key: `${p}_name`,
      label: `${P} Name (Avoid titles like Mr., Mrs., Dr., Prof.)`,
      type: 'text',
      step,
      required: true,
      preset: 'name',
      maps: `${p}_name`,
      rules: req,
    },
    {
      key: `${p}_education`,
      label: `${P} Educational Qualification`,
      type: 'select',
      step,
      required: true,
      list: 'Education',
      maps: `${p}_education`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_occupation`,
      label: `${P} Profession`,
      type: 'select',
      step,
      required: true,
      list: 'Occupation',
      maps: `${p}_occupation`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_designation`,
      label: `${P} Designation`,
      type: 'text',
      step,
      required: true,
      maps: `${p}_designation`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_organisation`,
      label: `${P} Organization Name`,
      type: 'text',
      step,
      required: true,
      maps: `${p}_organisation`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_mobile`,
      label: `${P} Mobile No`,
      type: 'mobile',
      step,
      required: true,
      maps: `${p}_mobile`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_email`,
      label: `${P} Email ID`,
      type: 'email',
      step,
      required: true,
      maps: `${p}_email`,
      rules: req,
      width: 'half',
    },
    {
      key: `${p}_nationality`,
      label: `${P} Nationality`,
      type: 'select',
      step,
      required: true,
      list: 'Nationality',
      maps: `${p}_nationality`,
      rules: req,
      width: 'half',
    },
  ];
  if (!opts.alumni) return out;
  const alum = [
    {
      logic: 'all' as const,
      action: 'show' as const,
      conditions: [{ field: `${p}_alumnus`, op: 'eq' as const, value: 'Yes' }],
    },
  ];
  out.push({
    key: `${p}_alumnus`,
    label: `${P} an Alumnus of the School`,
    type: 'select',
    step,
    required: true,
    list: 'YesNo',
    maps: `${p}_dps_alumni`,
    rules: req,
    width: 'half',
  });
  if (p === 'mother')
    out.push({
      key: 'mother_maiden_name',
      label: "Mother's Maiden Name",
      type: 'text',
      step,
      required: true,
      rules: alum,
      copy: true,
      width: 'half',
    });
  out.push(
    {
      key: `${p}_cbse_roll`,
      label: 'CBSE Roll No (XII)',
      type: 'text',
      step,
      required: true,
      preset: 'cbse_roll',
      rules: alum,
      maps: `${p}_alumni_cbse_roll_no`,
      width: 'half',
    },
    {
      key: `${p}_passout_year`,
      label: 'Pass Out Year',
      type: 'text',
      step,
      required: true,
      preset: 'year',
      rules: alum,
      maps: `${p}_alumni_passing_year`,
      width: 'half',
    },
    {
      key: `${p}_alumni_class`,
      label: 'Class',
      type: 'select',
      step,
      required: true,
      list: 'AlumniClass',
      rules: alum,
      maps: `${p}_alumni_passing_class`,
      width: 'half',
    },
  );
  return out;
};

