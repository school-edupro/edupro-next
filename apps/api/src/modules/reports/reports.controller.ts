import { Body, Controller, Get, Param, Post, Query } from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiTags } from '@nestjs/swagger';
import { DATASETS, mayUseDataset, rendererOrNull } from '@edupro/db';
import { RequirePermission } from '../../common/access/require-permission.decorator';
import { DomainError } from '../../common/errors/domain-error';
import { ReqCtx, type RequestContext } from '../../common/http/request-context';
import { CreateExportDto, ListExportsQueryDto, RowsQueryDto } from './reports.dto';
import { REPORTS } from './reports.permissions';
import { ReportsService } from './reports.service';

@ApiTags('reports')
@ApiBearerAuth()
@Controller('reports')
export class ReportsController {
  constructor(private readonly reports: ReportsService) {}

  @Get('datasets')
  @ApiOperation({ summary: 'Datasets the caller may export' })
  @RequirePermission(REPORTS.exportView, { description: 'View and download exports' })
  datasets(@ReqCtx() ctx: RequestContext) {
    const held = ctx.permissions ?? new Set<string>();
    return {
      data: Object.values(DATASETS)
        .filter((d) => mayUseDataset(held, d))
        .map((d) => ({
          id: d.id,
          title: d.title,
          columns: d.columns.map((c) => c.header),
          maxRows: d.maxRows,
        })),
    };
  }

  @Get('datasets/:id/rows')
  @ApiOperation({ summary: 'Run a dataset live for a screen (Sprint 15 report framework)' })
  @RequirePermission(REPORTS.exportView)
  rows(@ReqCtx() ctx: RequestContext, @Param('id') id: string, @Query() q: RowsQueryDto) {
    const { limit, ...params } = q;
    return this.reports.rows(ctx, id, params, limit);
  }

  @Get('exports')
  @RequirePermission(REPORTS.exportView)
  async list(@ReqCtx() ctx: RequestContext, @Query() q: ListExportsQueryDto) {
    // the exports the caller may open (see status); families (no export.create) their own only
    const { rows, total } = await this.reports.list(
      ctx,
      q,
      !ctx.permissions?.has(REPORTS.exportCreate),
    );
    return { data: rows, page: { number: q.page, size: q.size, total } };
  }

  @Post('exports')
  @ApiOperation({ summary: 'Request an export; the file is generated by a worker' })
  @RequirePermission(REPORTS.exportCreate, { description: 'Request PDF, Excel and CSV exports' })
  create(@ReqCtx() ctx: RequestContext, @Body() body: CreateExportDto) {
    // report cards are made from their own route, which checks the requester's classes
    const own = rendererOrNull(body.dataset)?.ownRoute;
    if (own)
      throw new DomainError('validation-failed', `This document is made from ${own}`, {
        status: 400,
      });
    return this.reports.create(ctx, body);
  }

  @Post('exports/instant')
  @ApiOperation({ summary: 'A list report as Excel, CSV or PDF, made at once (no worker)' })
  @RequirePermission(REPORTS.exportCreate)
  async instant(@ReqCtx() ctx: RequestContext, @Body() body: CreateExportDto) {
    const f = await this.reports.instant(ctx, body);
    return { filename: f.filename, contentType: f.contentType, base64: f.bytes.toString('base64') };
  }

  @Get('exports/:id')
  @ApiOperation({
    summary:
      'Export status and, when ready, a signed download URL: the requester, a holder of the dataset permission, or for a report card whoever sees all its pupils',
  })
  @RequirePermission(REPORTS.exportView)
  status(@ReqCtx() ctx: RequestContext, @Param('id') id: string) {
    return this.reports.status(ctx, id);
  }
}
