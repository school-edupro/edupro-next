#!/usr/bin/env node
/**
 * The mobile app's generated sources (docs/design/89, ADR-015): nothing is copied by hand from the web apps.
 *
 *   lib/theme/tokens.g.dart       the design system's colours, spacing, radii and type (packages/ui tokens)
 *   lib/l10n/menu_hindi.g.dart    Hindi for the menus' words (@edupro/menus labels, the web apps' dictionaries)
 *   lib/api/endpoints.g.dart      a typed method for each API operation the app lists in api-operations.txt,
 *                                 with classes for their request bodies (apps/api/openapi.json)
 *
 * Usage:  node scripts/mobile/generate.mjs            write the files
 *         node scripts/mobile/generate.mjs --check    fail when a file is stale or a listed operation is gone
 * The OpenAPI file comes from `pnpm --filter @edupro/api openapi:export` (or the built dist/openapi-export.js).
 */
import { createRequire } from 'node:module';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const mobile = join(root, 'apps', 'mobile');
const check = process.argv.includes('--check');
const header = (from) =>
  `// GENERATED by scripts/mobile/generate.mjs from ${from} — do not edit by hand.\n// ignore_for_file: type=lint\n`;

// ---------------------------------------------------------------- theme
function theme() {
  const css = ['colors.css', 'spacing.css', 'typography.css']
    .map((f) => readFileSync(join(root, 'packages', 'ui', 'src', 'tokens', f), 'utf8'))
    .join('\n');
  const vars = new Map();
  for (const m of css.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) vars.set(m[1], m[2].trim());
  const resolve = (v, depth = 0) => {
    const ref = /^var\(--([a-z0-9-]+)\)$/.exec(v);
    return ref && depth < 10 && vars.has(ref[1]) ? resolve(vars.get(ref[1]), depth + 1) : v;
  };
  const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  const lines = [];
  for (const [name, raw] of vars) {
    const v = resolve(raw);
    const hex = /^#([0-9a-f]{6})$/i.exec(v);
    if (hex) {
      lines.push(`  static const Color ${camel(name)} = Color(0xFF${hex[1].toUpperCase()});`);
      continue;
    }
    const px = /^(\d+(?:\.\d+)?)px$/.exec(v);
    if (px && /^(sp|radius|fs)-/.test(name))
      lines.push(`  static const double ${camel(name)} = ${Number(px[1])};`);
    const fw = /^(\d{3})$/.exec(v);
    if (fw && name.startsWith('fw-'))
      lines.push(`  static const FontWeight ${camel(name)} = FontWeight.w${fw[1]};`);
  }
  const family = (name) => /'([^']+)'/.exec(vars.get(name) ?? '')?.[1] ?? 'sans-serif';
  return `${header('packages/ui/src/tokens')}
import 'package:flutter/painting.dart';

/** The Mobilise Design System tokens, as the web apps' CSS has them. */
abstract final class Tokens {
${lines.join('\n')}
  static const String fontHeading = '${family('font-heading')}';
  static const String fontBody = '${family('font-body')}';
}
`;
}

// ---------------------------------------------------------------- the menus' Hindi
function menuHindi() {
  const require = createRequire(import.meta.url);
  const menus = require(join(root, 'packages', 'menus', 'dist', 'index.js'));
  const words = new Set();
  for (const g of menus.STAFF_MENU) {
    words.add(g.label);
    for (const i of g.items) {
      words.add(i.label);
      words.add(i.help);
    }
  }
  for (const g of menus.FAMILY_MENU) {
    words.add(g.label.parent);
    words.add(g.label.student);
    for (const i of g.items) words.add(i.label);
  }
  const dict = new Map();
  for (const app of ['parent', 'teacher']) {
    const src = readFileSync(join(root, 'apps', app, 'lib', 'i18n.ts'), 'utf8');
    const re =
      /^\s+(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|([A-Za-z_][A-Za-z0-9_]*)):\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"),?$/gm;
    for (const m of src.matchAll(re)) {
      const k = (m[1] ?? m[2] ?? m[3]).replace(/\\'/g, "'");
      const v = (m[4] ?? m[5]).replace(/\\'/g, "'");
      if (!dict.has(k)) dict.set(k, v);
    }
  }
  const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
  const pairs = [...words]
    .filter((w) => dict.has(w))
    .sort()
    .map((w) => `  ${q(w)}: ${q(dict.get(w))},`);
  return `${header("@edupro/menus and the web apps' dictionaries")}
/** Hindi for the menus' labels and help (the English text is the key; a word without Hindi stays English). */
const Map<String, String> menuHindi = {
${pairs.join('\n')}
};
`;
}

// ---------------------------------------------------------------- the API client
function api() {
  const specPath = join(root, 'apps', 'api', 'openapi.json');
  if (!existsSync(specPath))
    throw new Error(
      'apps/api/openapi.json is missing: run pnpm --filter @edupro/api openapi:export',
    );
  const spec = JSON.parse(readFileSync(specPath, 'utf8'));
  // `OperationId` (JSON) or `OperationId !file` (the answer is a file: report cards, receipts, attachments)
  const lines = readFileSync(join(mobile, 'api-operations.txt'), 'utf8')
    .split('\n')
    .map((l) => l.replace(/#.*/, '').trim())
    .filter(Boolean);
  const files = new Set(
    lines.filter((l) => / !file$/.test(l)).map((l) => l.replace(/ !file$/, '')),
  );
  const wanted = lines.map((l) => l.replace(/ !file$/, ''));
  const byId = new Map();
  const twice = new Set();
  for (const [path, methods] of Object.entries(spec.paths))
    for (const [method, op] of Object.entries(methods))
      if (op.operationId) {
        if (byId.has(op.operationId)) twice.add(op.operationId);
        byId.set(op.operationId, { path, method: method.toUpperCase(), op });
      }
  // two controllers with the same class name give two operations one id: rename one of the classes
  const ambiguous = wanted.filter((id) => twice.has(id));
  if (ambiguous.length)
    throw new Error(
      `api-operations.txt names operation ids the API uses twice: ${ambiguous.join(', ')}`,
    );
  const missing = wanted.filter((id) => !byId.has(id));
  if (missing.length)
    throw new Error(
      `api-operations.txt names operations the API no longer has: ${missing.join(', ')}`,
    );

  const schemas = spec.components?.schemas ?? {};
  // Two request classes with one name in different modules share one schema in the spec (the last one wins), so
  // a body the app sends must have a class name of its own in apps/api/src.
  const classNames = new Map();
  const scan = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) scan(p);
      else if (e.name.endsWith('.ts'))
        for (const m of readFileSync(p, 'utf8').matchAll(/export class (\w+)/g))
          classNames.set(m[1], (classNames.get(m[1]) ?? 0) + 1);
    }
  };
  scan(join(root, 'apps', 'api', 'src'));
  const refsOf = (schema, seen = new Set()) => {
    if (!schema || typeof schema !== 'object') return seen;
    if (schema.$ref) {
      const n = schema.$ref.split('/').pop();
      if (!seen.has(n)) {
        seen.add(n);
        refsOf(schemas[n], seen);
      }
    }
    for (const v of Object.values(schema)) if (v && typeof v === 'object') refsOf(v, seen);
    return seen;
  };
  const shared = wanted.flatMap((id) =>
    [...refsOf(byId.get(id).op.requestBody ?? {})]
      .filter((n) => (classNames.get(n) ?? 0) > 1)
      .map((n) => `${id} (${n})`),
  );
  if (shared.length)
    throw new Error(
      `request classes named in more than one API module (give them names of their own): ${shared.join(', ')}`,
    );
  const classes = new Map();
  const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
  const ident = (s) => {
    const x = s.replace(/[^A-Za-z0-9_]/g, '_');
    return ['in', 'is', 'class', 'default', 'new', 'enum', 'switch', 'for'].includes(x)
      ? `${x}_`
      : x;
  };
  // a request body as a Dart class (nested objects become classes of their own)
  const dartType = (schema, name) => {
    if (!schema) return 'Object?';
    if (schema.$ref) return classFor(schema.$ref.split('/').pop());
    if (schema.type === 'string') return 'String';
    if (schema.type === 'integer') return 'int';
    if (schema.type === 'number') return 'num';
    if (schema.type === 'boolean') return 'bool';
    if (schema.type === 'array') return `List<${dartType(schema.items, `${name}Item`)}>`;
    if (schema.type === 'object' && schema.properties) return classOf(name, schema);
    return 'Object?';
  };
  const classFor = (ref) => (classes.has(ref) ? ref : classOf(ref, schemas[ref]));
  function classOf(name, schema) {
    if (classes.has(name)) return name;
    classes.set(name, null);
    const req = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([prop, s]) => {
      const t = dartType(s, `${name}${pascal(ident(prop))}`);
      const optional = !req.has(prop);
      const nested = classes.has(t) && classes.get(t) !== undefined;
      const list = /^List<(\w+)>$/.exec(t);
      const listOfClass = list && classes.has(list[1]);
      const json = nested
        ? `${ident(prop)}${optional ? '?' : ''}.toJson()`
        : listOfClass
          ? `${ident(prop)}${optional ? '?' : ''}.map((x) => x.toJson()).toList()`
          : ident(prop);
      return {
        prop,
        field: ident(prop),
        type: `${t}${optional && !t.endsWith('?') ? '?' : ''}`,
        optional,
        json,
        doc: s.description,
      };
    });
    const body = [
      `/** ${schema.description ?? `The ${name} the API takes.`} */`,
      `class ${name} {`,
      `  const ${name}(${fields.length ? `{${fields.map((f) => `${f.optional ? '' : 'required '}this.${f.field}`).join(', ')}}` : ''});`,
      ...fields.map(
        (f) =>
          `${f.doc ? `  /// ${f.doc.replace(/\n/g, ' ')}\n` : ''}  final ${f.type} ${f.field};`,
      ),
      '  Map<String, Object?> toJson() => {',
      ...fields.map((f) =>
        f.optional
          ? `        if (${f.field} != null) '${f.prop}': ${f.json},`
          : `        '${f.prop}': ${f.json},`,
      ),
      '      };',
      '}',
    ].join('\n');
    classes.set(name, body);
    return name;
  }

  const methods = wanted.map((id) => {
    const { path, method, op } = byId.get(id);
    const [ctrl, fn] = id.split('_');
    const name = ident(
      `${ctrl.replace(/Controller$/, '').replace(/^./, (c) => c.toLowerCase())}${pascal(fn ?? '')}`,
    );
    const rel = path.replace(/^\/api\/v1/, '');
    const params = op.parameters ?? [];
    const args = [];
    const pathParams = params.filter((p) => p.in === 'path');
    const query = params.filter((p) => p.in === 'query');
    for (const p of pathParams) args.push(`required String ${ident(p.name)}`);
    for (const p of query) {
      // a field of more than one type is already `Object?`: no second `?`
      const type = dartType(p.schema, 'Q');
      args.push(
        `${p.required ? 'required ' : ''}${type}${p.required || type.endsWith('?') ? '' : '?'} ${ident(p.name)}`,
      );
    }
    const bodyRef = op.requestBody?.content?.['application/json']?.schema?.$ref;
    const bodyType = bodyRef ? classFor(bodyRef.split('/').pop()) : null;
    if (bodyType) args.unshift(`required ${bodyType} body`);
    const url = rel.replace(/\{([^}]+)\}/g, (_, p) => `\${Uri.encodeComponent(${ident(p)})}`);
    const q = query.length
      ? `, query: {${query.map((p) => (p.required ? `'${p.name}': ${ident(p.name)}` : `if (${ident(p.name)} != null) '${p.name}': ${ident(p.name)}`)).join(', ')}}`
      : '';
    const summary = (op.summary ?? '').replace(/\n/g, ' ');
    const file = files.has(id);
    return `  /// ${method} ${rel}${summary ? ` — ${summary}` : ''}
  Future<${file ? 'ApiFile' : 'dynamic'}> ${name}(${args.length ? `{${args.join(', ')}}` : ''}) =>
      _t.${file ? 'file' : 'send'}('${method}', '${url}'${bodyType ? ', body: body.toJson()' : ''}${q});`;
  });
  return `${header('apps/api/openapi.json and apps/mobile/api-operations.txt')}
import 'api_transport.dart';

/** The API operations the app uses, typed from the API's own description (the app never writes a URL by hand). */
class EduProApi {
  EduProApi(this._t);
  final ApiTransport _t;

${methods.join('\n\n')}
}

${[...classes.values()].filter(Boolean).join('\n\n')}
`;
}

// ---------------------------------------------------------------- write or check
const outputs = [
  ['lib/theme/tokens.g.dart', theme],
  ['lib/l10n/menu_hindi.g.dart', menuHindi],
  ['lib/api/endpoints.g.dart', api],
];
let stale = 0;
for (const [rel, make] of outputs) {
  const target = join(mobile, rel);
  const next = make();
  const now = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (check) {
    if (now !== next) {
      stale += 1;
      console.error(`stale: apps/mobile/${rel} (run node scripts/mobile/generate.mjs)`);
    }
  } else if (now !== next) {
    writeFileSync(target, next);
    console.log(`wrote apps/mobile/${rel}`);
  }
}
if (stale) process.exit(1);
if (check) console.log('mobile generated sources are up to date');
